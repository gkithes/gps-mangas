import { settings } from "./store.js";

export const LANGS = {
  el: { name: "Ελληνικά", locale: "el-GR", comma: true },
  en: { name: "English", locale: "en-US", comma: false },
  es: { name: "Español", locale: "es-ES", comma: true },
  fr: { name: "Français", locale: "fr-FR", comma: true },
  de: { name: "Deutsch", locale: "de-DE", comma: true },
  it: { name: "Italiano", locale: "it-IT", comma: true },
  pt: { name: "Português", locale: "pt-PT", comma: true },
  ar: { name: "عربي لبناني", locale: "ar-LB", comma: false, rtl: true },
};

export function lang() {
  if (settings.uiLang && settings.uiLang !== "auto" && LANGS[settings.uiLang]) return settings.uiLang;
  const device = (navigator.language || "el").slice(0, 2).toLowerCase();
  return LANGS[device] ? device : "en";
}
export const locale = (code = lang()) => LANGS[code]?.locale || "en-US";
export const usesComma = () => LANGS[lang()].comma;
export const isRtl = () => !!LANGS[lang()].rtl;
// «Κανονικό GPS»: χωρίς ατάκες και με ευγενικά κείμενα
export const isNormalGps = () => settings.style === "normal" || settings.mode === "plain";

// t("nav.inDist", { d: "200 μέτρα", instr: "…" })
export function t(key, vars = {}) {
  const l = lang();
  const polite = isNormalGps() && (TEXT[l]?.[`${key}.plain`] ?? TEXT.en[`${key}.plain`]);
  const s = polite || (TEXT[l]?.[key] ?? TEXT.en[key] ?? TEXT.el[key] ?? key);
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}

// Κείμενα που είναι γραμμένα στη σελίδα (index.html):
//   data-i18n="key" → κείμενο, data-i18n-ph → placeholder, data-i18n-aria → aria-label
export function applyStatic(root = document) {
  document.documentElement.lang = lang();
  document.documentElement.dir = isRtl() ? "rtl" : "ltr"; // Αραβικά: από δεξιά προς τα αριστερά
  root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
}

